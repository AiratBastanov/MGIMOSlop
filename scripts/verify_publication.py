"""Verify a curated checkout, reader links and every outgoing Git object.

No credential values or raw suspicious content are printed. Private JSON paths
are optional inputs for exact-value checks; the public manifest is the boundary.
"""
import argparse
import hashlib
from html.parser import HTMLParser
import json
from pathlib import Path
import re
import subprocess
from urllib.parse import unquote, urlsplit

from export_publication import selected_files

ROOT = Path(__file__).resolve().parents[1]
LIMIT = 100 * 1024 * 1024
FORBIDDEN = {'.local', '.git', '.venv', 'node_modules', '__pycache__', 'evidence', 'pgdata', 'staticfiles'}
PATTERNS = [rb'-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----',
            rb'gh[pousr]_[A-Za-z0-9]{30,}', rb'github_pat_[A-Za-z0-9_]{50,}',
            rb'AKIA[0-9A-Z]{16}']
READER_DOCS = ['README.md', 'AGENTS.md', 'deploy/README.md',
               *['docs/' + name + '.md' for name in ('SETUP', 'DEMO', 'ARCHITECTURE', 'AI_ASSISTANT',
                 'DEVELOPMENT_PROCESS', 'VALIDATION', 'RIGHTS', 'THIRD_PARTY_NOTICES')], 'docs/creation-process.html']


def git(*args):
    return subprocess.check_output(['git', *args], cwd=ROOT, stderr=subprocess.PIPE)


def secrets_from(path):
    value = json.loads(path.read_text(encoding='utf-8'))
    credentials = 'credential' in path.name.lower()
    found = []
    def visit(data, sensitive=False):
        if isinstance(data, dict):
            for key, val in data.items():
                visit(val, sensitive or credentials or bool(re.search('password|secret|token', key, re.I)))
        elif isinstance(data, list):
            for val in data: visit(val, sensitive)
        elif isinstance(data, str) and sensitive and len(data) >= 8:
            found.append(data.encode('utf-8'))
    visit(value)
    return found


def slug(text):
    text = re.sub(r'<[^>]+>', '', text).strip().lower().replace('`', '')
    return re.sub(r'[^\w\- ]', '', text, flags=re.UNICODE).replace(' ', '-')


class Links(HTMLParser):
    def __init__(self):
        super().__init__(); self.links = []; self.ids = set(); self.visible = []
    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if 'id' in attrs: self.ids.add(attrs['id'])
        for key in ('href', 'src'):
            if key in attrs: self.links.append(attrs[key])
    def handle_data(self, data):
        self.visible.append(data)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--outgoing', help='Commit to compare with all existing remote refs.')
    parser.add_argument('--secret-file', action='append', default=[])
    parser.add_argument('--report', help='Optional private result path outside the selected files.')
    args = parser.parse_args()
    files = selected_files(ROOT)
    selected = {p.relative_to(ROOT).as_posix() for p in files}
    secrets = [value for path in args.secret_file for value in secrets_from(Path(path))]
    errors, reviewed = [], 0

    def inspect(data, name):
        nonlocal reviewed
        reviewed += 1
        if len(data) >= LIMIT: errors.append('oversized: ' + name)
        if any(value in data for value in secrets): errors.append('private-value: ' + name)
        if any(re.search(pattern, data) for pattern in PATTERNS): errors.append('credential-pattern: ' + name)

    for path in files:
        rel = path.relative_to(ROOT).as_posix()
        if set(path.relative_to(ROOT).parts) & FORBIDDEN or path.suffix.lower() in {'.dump', '.zip', '.har', '.eml', '.sqlite3', '.gguf', '.safetensors', '.log'}:
            errors.append('forbidden-path: ' + rel)
        inspect(path.read_bytes(), rel)
    spec = json.loads((ROOT / 'scripts/publication-files.json').read_text(encoding='utf-8'))
    if (ROOT / 'AGENTS.md').read_text(encoding='utf-8') != '\n'.join(spec['public_instructions']):
        errors.append('AGENTS.md: use the public instructions generated by export_publication.py')
    for pattern in spec['include']:
        if not any(p.is_file() for p in ROOT.glob(pattern)):
            errors.append('missing include: ' + pattern)
    for app in ('accounts', 'studies', 'student_requests', 'notifications', 'materials', 'profiles', 'workspaces', 'data_import'):
        if not list((ROOT / app / 'migrations').glob('0*.py')):
            errors.append('missing migrations: ' + app)
    assets = json.loads((ROOT / 'static/frontend/manifest.json').read_text(encoding='utf-8'))
    for item in assets.values():
        for name in [item['file'], *item.get('css', []), *item.get('assets', [])]:
            if 'static/frontend/' + name not in selected: errors.append('missing asset: ' + name)

    links_checked = 0
    for rel in READER_DOCS:
        path = ROOT / rel
        if not path.is_file(): errors.append('missing document: ' + rel); continue
        data = path.read_text(encoding='utf-8')
        if path.suffix == '.html':
            html = Links(); html.feed(data)
            links = html.links + re.findall(r"url\(['\"]?([^'\")]+)", data)
            prose = ' '.join(html.visible)
        else:
            clean = re.sub(r'```.*?```', '', data, flags=re.S)
            links = re.findall(r'\]\(([^\s)]+)(?:\s+"[^"]*")?\)', clean)
            prose = re.sub(r'\]\([^)]*\)', ']', clean)
            prose = re.sub(r'`[^`]*`', '', prose)
        if re.search(r'\bTASK\d+\b|\bS\d+\b|\b(?:evidence|gate|handoff)\b|NEW PASS|REUSED PASS|C:[\\/]Users[\\/]', prose, re.I):
            errors.append('internal reader label: ' + rel)
        for link in links:
            parts = urlsplit(unquote(link))
            if parts.scheme in ('https', 'http', 'mailto', 'tel'): continue
            if parts.scheme or link.startswith('//'):
                errors.append('non-browser link: ' + rel); continue
            target = (path.parent / parts.path).resolve() if parts.path else path
            if not target.is_relative_to(ROOT) or not target.exists():
                errors.append(f'broken link: {rel} -> {link}'); continue
            links_checked += 1
            if target.is_file() and target.relative_to(ROOT).as_posix() not in selected:
                errors.append(f'link outside selection: {rel} -> {link}')
            if parts.fragment and target.suffix in ('.md', '.html'):
                text = target.read_text(encoding='utf-8')
                if target.suffix == '.html':
                    parsed = Links(); parsed.feed(text); anchors = parsed.ids
                else:
                    anchors = {slug(line.lstrip('#').strip()) for line in text.splitlines() if re.match(r'^#{1,6} ', line)}
                    anchors |= set(re.findall(r'<a\s+id="([^"]+)"', text))
                if parts.fragment not in anchors: errors.append(f'broken anchor: {rel} -> {link}')

    from pypdf import PdfReader
    pdf = PdfReader(ROOT / 'docs/creation-process.pdf')
    for number, page in enumerate(pdf.pages, 1):
        if len(page.extract_text().strip()) < 50: errors.append('empty PDF page: ' + str(number))
        for ref in page.get('/Annots', []):
            action = ref.get_object().get('/A', {})
            if '/URI' in action and not str(action['/URI']).startswith(('https://', 'http://')):
                errors.append('private PDF URI: page ' + str(number))

    outgoing = 0
    if args.outgoing:
        tracked = set(git('ls-tree', '-r', '--name-only', args.outgoing).decode('utf-8').splitlines())
        if tracked != selected:
            errors.extend('commit extra: ' + p for p in sorted(tracked - selected))
            errors.extend('commit missing: ' + p for p in sorted(selected - tracked))
        for rel in sorted(tracked & selected):
            if git('show', args.outgoing + ':' + rel) != (ROOT / rel).read_bytes():
                errors.append('commit differs from candidate: ' + rel)
        objects = git('rev-list', '--objects', '--no-object-names', args.outgoing, '--not', '--remotes').decode().splitlines()
        meta = subprocess.check_output(['git', 'cat-file', '--batch-check=%(objectname) %(objecttype) %(objectsize)'],
                                       input=('\n'.join(objects) + '\n').encode(), cwd=ROOT, stderr=subprocess.PIPE)
        for line in meta.decode().splitlines():
            oid, kind, size = line.split()
            if int(size) >= LIMIT: errors.append('oversized outgoing object: ' + oid); continue
            if kind in ('blob', 'commit', 'tag'):
                inspect(git('cat-file', kind, oid), 'outgoing ' + oid)
                outgoing += 1
    result = {'files': len(files), 'bytes': sum(p.stat().st_size for p in files),
              'largest': max(({'path': p.relative_to(ROOT).as_posix(), 'bytes': p.stat().st_size} for p in files), key=lambda p: p['bytes']),
              'local_links': links_checked, 'pdf_pages': len(pdf.pages), 'secret_values_compared': len(secrets),
              'outgoing_objects_scanned': outgoing, 'errors': errors}
    if args.report:
        report = Path(args.report).resolve()
        if report.is_relative_to(ROOT) and report.relative_to(ROOT).as_posix() in selected:
            parser.error('Результат должен оставаться вне публичной выборки.')
        if report.exists(): parser.error('Файл результата уже существует.')
        report.parent.mkdir(parents=True, exist_ok=True)
        report.write_text(json.dumps(result, ensure_ascii=False, indent=2), encoding='utf-8')
    print(json.dumps(result, ensure_ascii=False, indent=2))
    raise SystemExit(bool(errors))


if __name__ == '__main__':
    main()
